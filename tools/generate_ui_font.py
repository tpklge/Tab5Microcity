#!/usr/bin/env python3
"""Reproducible minimal boot/UI font, including Portuguese and UI symbols."""
import hashlib,json
from pathlib import Path
from PIL import Image,ImageDraw,ImageFont
from fontTools.ttLib import TTFont
ROOT=Path(__file__).resolve().parents[1]
CODES=list(range(32,127))+list(range(160,256))+[0x2013,0x2014,0x2022,0x2190,0x2191,0x2192,0x2193,0x2212,0x2264]
SHA='b85c38ecea8a7cfb39c24e395a4007474fa5a4fc864f6ee33309eb4948d232d5'
MATH_SHA='80b61fd613d3519197e64fff6f7e71fdc7f3e6526440ea4115b554ef7fd59af7'
def generate():
    source=ROOT/'assets/fonts/NotoSans-Regular.ttf'
    if hashlib.sha256(source.read_bytes()).hexdigest()!=SHA:raise ValueError('unexpected font source SHA-256')
    math=ROOT/'assets/fonts/NotoSansMath-Regular.ttf'
    if hashlib.sha256(math.read_bytes()).hexdigest()!=MATH_SHA:raise ValueError('unexpected math font SHA-256')
    sources=[source,math];tt=[TTFont(str(p)) for p in sources];cmaps=[t.getBestCmap() for t in tt];fonts=[ImageFont.truetype(str(p),22) for p in sources]
    font_for={};glyph_ids={}
    for cp in CODES:
        index=next((i for i,cmap in enumerate(cmaps) if cp in cmap),None)
        if index is None:raise ValueError(f'missing source glyph U+{cp:04X}')
        font_for[cp]=index;glyph_ids[cp]=tt[index].getGlyphID(cmaps[index][cp])
        if not glyph_ids[cp]:raise ValueError('notdef glyph forbidden')
    bitmap=bytearray();descs=['{0}']
    for cp in CODES:
        font=fonts[font_for[cp]];ch=chr(cp);x0,y0,x1,y1=font.getbbox(ch,anchor='ls');w=x1-x0;h=y1-y0
        offset=len(bitmap);im=Image.new('L',(max(1,w),max(1,h)));ImageDraw.Draw(im).text((-x0,-y0),ch,font=font,anchor='ls',fill=255)
        pixels=[(p*15+127)//255 for p in im.getdata()] if w*h else []
        for i in range(0,len(pixels),2):bitmap.append((pixels[i]<<4)|(pixels[i+1] if i+1<len(pixels) else 0))
        descs.append(f'{{.bitmap_index={offset},.adv_w={round(font.getlength(ch)*16)},.box_w={w},.box_h={h},.ofs_x={x0},.ofs_y={-y1}}}')
    data='\n'.join(','.join(str(x) for x in bitmap[i:i+24])+',' for i in range(0,len(bitmap),24))
    joined=',\n'.join(descs);unicodes=','.join(str(cp-32) for cp in CODES)
    code=f'''/* Generated by tools/generate_ui_font.py; Noto Sans / Noto Sans Math, SIL OFL-1.1.
 * Copyright 2018 The Noto Project Authors. See assets/fonts/OFL.txt. */
#include "lvgl.h"
static const uint8_t bitmap[]={{\n{data}\n}};
static const lv_font_fmt_txt_glyph_dsc_t glyphs[]={{\n{joined}\n}};
static const uint16_t unicodes[]={{ {unicodes} }};
static const lv_font_fmt_txt_cmap_t cmaps[]={{ {{.range_start=32,.range_length={max(CODES)-31},.glyph_id_start=1,.unicode_list=unicodes,.glyph_id_ofs_list=NULL,.list_length={len(CODES)},.type=LV_FONT_FMT_TXT_CMAP_SPARSE_TINY}} }};
static const lv_font_fmt_txt_dsc_t descriptor={{.glyph_bitmap=bitmap,.glyph_dsc=glyphs,.cmaps=cmaps,.cmap_num=1,.bpp=4,.bitmap_format=0}};
const lv_font_t mc_font_ui={{.get_glyph_dsc=lv_font_get_glyph_dsc_fmt_txt,.get_glyph_bitmap=lv_font_get_bitmap_fmt_txt,.line_height=32,.base_line=8,.subpx=LV_FONT_SUBPX_NONE,.underline_position=-2,.underline_thickness=1,.dsc=&descriptor}};
'''
    (ROOT/'main/ui/fonts/mc_font_ui.c').write_text(code)
    (ROOT/'assets/fonts/coverage.json').write_text(json.dumps(dict(font='NotoSans-Regular',size=22,sha256=SHA,math_sha256=MATH_SHA,codepoints=CODES,glyph_ids=glyph_ids,source_by_codepoint={cp:sources[i].name for cp,i in font_for.items()},bitmap_bytes=len(bitmap)),indent=2)+'\n')
    preview=Image.new('RGB',(1100,230),'#182e38');d=ImageDraw.Draw(preview)
    for y,text in enumerate(['Português: ação, construção, água, polícia, saúde, população.','Á É Í Ó Ú Â Ê Ô Ã Õ Ç  á é í ó ú â ê ô ã õ ç','Câmera ← ↑ → ↓  •  Pausa  1×  2×  4×  −  +','Construções e overlays: atalhos visíveis, sem dropdown.']):
        x=24
        for ch in text:
            font=fonts[font_for[ord(ch)]];d.text((x,20+y*49),ch,font=font,fill='#eee7d5');x+=font.getlength(ch)
    preview.save(ROOT/'assets/fonts/preview-ptbr.png');print(f'{len(CODES)} glyphs; {len(bitmap)} bitmap bytes')
if __name__=='__main__':generate()
